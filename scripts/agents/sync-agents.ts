/**
 * Generates each tool's agent files from the shared role sources.
 *
 *   npm run agents:sync        (npx tsx scripts/agents/sync-agents.ts)
 *
 * Every role lives in agents/roles/<role>/:
 *   body.md                  the instructions, tool-neutral, written once
 *   claude.frontmatter.yml   frontmatter for .claude/agents/<role>.md
 *   omp.frontmatter.yml      frontmatter for .omp/agents/<role>.md
 *   claude.extra.md          optional, appended after the body for Claude Code
 *   omp.extra.md             optional, appended after the body for omp
 *
 * A role without a tool's frontmatter file is skipped for that tool. The
 * frontmatter is inserted verbatim (no YAML parsing). Output is deterministic,
 * so running this twice changes nothing; scripts/agents/sync-agents.test.ts fails if
 * a committed generated file drifts from what this would write.
 *
 * Touches no database and makes no network calls.
 */
import fs from "node:fs";
import path from "node:path";

export const ROOT = path.resolve(__dirname, "..", "..");
export const ROLES_DIR = path.join(ROOT, "agents", "roles");

export const TOOLS = [
  { tool: "claude", outDir: ".claude/agents" },
  { tool: "omp", outDir: ".omp/agents" },
] as const;

export type Tool = (typeof TOOLS)[number]["tool"];

export type GeneratedFile = {
  role: string;
  tool: Tool;
  /** Repo-relative output path, with forward slashes. */
  relPath: string;
  content: string;
};

/** Strips trailing newlines so each part is joined with exact spacing. */
function trimEnd(text: string): string {
  return text.replace(/\s+$/, "");
}

/** Pure: builds one agent file from its parts. */
export function renderAgent(opts: {
  role: string;
  frontmatter: string;
  body: string;
  extra?: string | null;
}): string {
  const header = `<!-- Generated by scripts/agents/sync-agents.ts from agents/roles/${opts.role}/. Edit there, then run npm run agents:sync. -->`;
  const parts = [`---\n${trimEnd(opts.frontmatter)}\n---`, header, trimEnd(opts.body)];
  if (opts.extra && trimEnd(opts.extra) !== "") parts.push(trimEnd(opts.extra));
  return `${parts.join("\n\n")}\n`;
}

function readIfExists(file: string): string | null {
  return fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
}

/** Every generated file the role sources call for, sorted by path. */
export function expectedFiles(rolesDir: string = ROLES_DIR): GeneratedFile[] {
  const roles = fs
    .readdirSync(rolesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  const files: GeneratedFile[] = [];
  for (const role of roles) {
    const dir = path.join(rolesDir, role);
    const body = readIfExists(path.join(dir, "body.md"));
    if (body === null) throw new Error(`agents/roles/${role}/body.md is missing`);
    for (const { tool, outDir } of TOOLS) {
      const frontmatter = readIfExists(path.join(dir, `${tool}.frontmatter.yml`));
      if (frontmatter === null) continue;
      const extra = readIfExists(path.join(dir, `${tool}.extra.md`));
      files.push({
        role,
        tool,
        relPath: `${outDir}/${role}.md`,
        content: renderAgent({ role, frontmatter, body, extra }),
      });
    }
  }
  return files.sort((a, b) => a.relPath.localeCompare(b.relPath));
}

function main(): void {
  for (const file of expectedFiles()) {
    const target = path.join(ROOT, file.relPath);
    if (readIfExists(target) === file.content) {
      console.log(`unchanged  ${file.relPath}`);
      continue;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, file.content);
    console.log(`wrote      ${file.relPath}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main();
}
